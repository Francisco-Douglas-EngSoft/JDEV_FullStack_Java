public class loop_while {
    public static void main(String[] args) {
        int contador = 0;

        while (contador < 5) {
            System.out.println("Contador: " + contador);
            contador++;
        }
        //o operador while é usado para criar um loop que continua enquanto a condição especificada for verdadeira. No exemplo acima, o loop continuará enquanto o valor de "contador" for menor que 5. A cada iteração, o valor de "contador" é incrementado em 1, e o loop termina quando "contador" atinge 5.
    }
    
}
