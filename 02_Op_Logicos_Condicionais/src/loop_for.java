public class loop_for {
    public static void main(String[] args) {
        for (int i = 0; i < 5; i++) {
            System.out.println("Contador: " + i);
        }
        //o operador for é usado para criar um loop que itera um número específico de vezes. No exemplo acima, o loop continuará enquanto o valor de "i" for menor que 5. A cada iteração, o valor de "i" é incrementado em 1, e o loop termina quando "i" atinge 5.
    }
}
