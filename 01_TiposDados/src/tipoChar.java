public class tipoChar {
    public static void main(String[] args){
        //Tipo char apresenta apenas uma Unica letra
        char letra = 'F';
        System.out.println("Tipo Char: "+letra);

        //Exemplo Sabendo se e homen ou mulher
        char homen = 'H';
        char mulher = 'M';
        System.out.println("Homen = "+homen);
        System.out.println("Mulher = "+mulher);
    }
}
